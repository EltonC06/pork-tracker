/* eslint-disable @typescript-eslint/no-require-imports -- Pure TypeScript helper harness. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename)
const { periodRange, monthLabel, matchesListSearch, sortDateItems, groupDateItems, paginateItems } = require('../src/lib/dateList.ts')
const { selectInvoices, invoiceCardKey } = require('../src/lib/invoiceList.ts')
assert.deepEqual(periodRange('month', '2028-02'), { start: '2028-02-01', end: '2028-02-29' })
assert.deepEqual(periodRange('last_month', '', '', '', '2027-01-01'), { start: '2026-12-01', end: '2026-12-31' })
assert.deepEqual(periodRange('last_30_days', '', '', '', '2027-01-01'), { start: '2026-12-03', end: '2027-01-01' })
assert.deepEqual(periodRange('this_year', '', '', '', '2027-01-01'), { start: '2027-01-01', end: '2027-12-31' })
assert.deepEqual(periodRange('custom', '', '2026-12-31', ''), { start: '2026-12-31', end: '9999-12-31' })
assert.ok(monthLabel('2026-12-01').toLowerCase().includes('dezembro'))
assert.ok(matchesListSearch('alimentacao', 'Alimenta\u00e7\u00e3o'))
const invoices = [{ id: 'a', statement_month: '2027-01-01', card_label: 'Inter', card_last_four: '1234' }, { id: 'b', statement_month: '2027-01-01', card_label: 'Inter adicional', card_last_four: '5678' }, { id: 'c', statement_month: '2026-12-01', card_label: 'Inter', card_last_four: '1234' }]
assert.equal(selectInvoices([], '2027-01').length, 0)
assert.equal(selectInvoices(invoices, '2027-01').length, 2)
assert.deepEqual(selectInvoices(invoices, '2027-01', invoiceCardKey(invoices[0])).map(row => row.id), ['a'])
assert.equal(selectInvoices(invoices, '2027-02', invoiceCardKey(invoices[0])).length, 0)
assert.deepEqual(selectInvoices(invoices, '2027-01', '', 'b').map(row => row.id), ['b'])
assert.equal(selectInvoices(invoices, '2027-01', '', 'missing').length, 0)
const items = [{ id: 'purchase', date: '2026-12-31', description: 'Mercado', amount: 100 }, { id: 'credit', date: '2027-01-01', description: 'Estorno', amount: -10 }, { id: 'older', date: '2026-11-01', description: 'Parcela', amount: 40 }]
const sorted = sortDateItems(items, 'date_desc', row => row.amount)
assert.equal(sorted[0].id, 'credit')
assert.equal(sortDateItems(items, 'amount_asc', row => row.amount)[0].id, 'credit')
assert.equal(sortDateItems(items, 'description', row => row.amount)[0].id, 'credit')
assert.equal(groupDateItems(sorted, 'week').length, 2)
assert.equal(groupDateItems(sorted, 'week')[0].key, '2026-12-28')
assert.equal(groupDateItems(sorted, 'month').length, 3)
assert.equal(groupDateItems(sorted, 'none')[0].items.reduce((sum, row) => sum + row.amount, 0), 130)
assert.equal(groupDateItems([], 'none').length, 0)
const many = Array.from({ length: 25 }, (_, i) => ({ id: String(i), date: '2027-01-01', amount: i === 24 ? -100 : 100 }))
const page = paginateItems(many, 1)
assert.equal(page.items.length, 5)
assert.equal(groupDateItems(page.items, 'day')[0].items.reduce((sum, row) => sum + row.amount, 0), 300)
assert.equal(paginateItems(many.slice(0, 2), 1).page, 0)
assert.equal(paginateItems([], 9).items.length, 0)
const ref = selectInvoices(invoices, '2027-01', '', 'a')
assert.equal(ref.length, 1)
assert.equal(items.filter(item => item.date >= periodRange('all', '').start).length, 3)
console.log('date-list: passed period boundaries, card selection, credits, grouping, ordering, search and visible-page subtotals')
